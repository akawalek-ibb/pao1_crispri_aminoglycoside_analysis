cat("Model:  ", model_file, "\n", sep = "")
cat("Output: ", output_file, "\n\n", sep = "")

message("Reading guide table...")
input_dt <- fread(
  input_file,
  header = TRUE,
  showProgress = TRUE
)

if (nrow(input_dt) == 0L) {
  stop("The input file contains no guide rows.")
}

message(
  "Loaded ",
  format(nrow(input_dt), big.mark = ","),
  " guide rows across ",
  format(uniqueN(as.character(input_dt$locus_tag)), big.mark = ","),
  " loci."
)

message("Loading trained model bundle...")
bundle <- readRDS(model_file)

cat(
  "Deployed feature set: ",
  bundle$model$deployed_feature_set,
  "\n",
  sep = ""
)
cat(
  "Lambda:               ",
  format(bundle$model$lambda, digits = 8),
  "\n",
  sep = ""
)
cat(
  "Uses offset:          ",
  bundle$model$use_offset,
  "\n",
  sep = ""
)
cat(
  "Uses off-target:      ",
  bundle$model$use_offtarget,
  "\n\n",
  sep = ""
)

scored_dt <- score_guide_table(
  input_dt = input_dt,
  bundle = bundle
)

message("Writing scored table...")
write_scored_table(scored_dt, output_file)

status_summary <- scored_dt[
  ,
  .N,
  by = kawalek_score_status
][order(-N)]

elapsed <- as.numeric(
  difftime(Sys.time(), start_time, units = "secs")
)

cat("\nScoring summary\n")
cat("---------------\n")
cat(
  "Input rows:   ",
  format(nrow(scored_dt), big.mark = ","),
  "\n",
  sep = ""
)
cat(
  "Scored rows:  ",
  format(
    sum(is.finite(scored_dt$kawalek_efficacy_score)),
    big.mark = ","
  ),
  "\n",
  sep = ""
)
cat(
  "Genes/loci:   ",
  format(
    uniqueN(as.character(scored_dt$locus_tag)),
    big.mark = ","
  ),
  "\n",
  sep = ""
)
cat(
  "Elapsed time: ",
  sprintf("%.2f seconds", elapsed),
  "\n\n",
  sep = ""
)

print(status_summary)

# List unscored rows in R; no separate summary file is written.
problem_rows <- which(
  is.na(scored_dt$kawalek_score_status) |
    scored_dt$kawalek_score_status != "scorable" |
    !is.finite(scored_dt$kawalek_efficacy_score)
)
scoring_problems <- scored_dt[
  problem_rows,
  .(
    input_row = problem_rows,
    locus_tag,
    sgrna,
    pam,
    issue = kawalek_score_status
  )
]
scoring_problems[issue == "scorable", issue := "non_finite_prediction"]
scoring_problems[is.na(issue), issue := "unknown_scoring_status"]

if (nrow(scoring_problems) > 0L) {
  cat("\nGuide rows with scoring problems:\n")
  print(scoring_problems, nrows = nrow(scoring_problems))
  warning(
    nrow(scoring_problems),
    " guide row(s) could not be scored. See the console listing above.",
    call. = FALSE,
    immediate. = TRUE
  )
} else {
  message("All guide rows were scored successfully.")
}

cat("\nSaved scored table:\n", output_file, "\n", sep = "")

if (isTRUE(ASSIGN_RESULT_OBJECT)) {
  assign(
    RESULT_OBJECT_NAME,
    scored_dt,
    envir = .GlobalEnv
  )
  
  cat(
    "\nR object available as:\n",
    RESULT_OBJECT_NAME,
    "\n",
    sep = ""
  )
}
