strip_table_extensions <- function(path) {
  x <- basename(path)
  x <- sub("\\.gz$", "", x, ignore.case = TRUE)
  x <- sub("\\.(csv|tsv|txt)$", "", x, ignore.case = TRUE)
  x
}

make_default_output <- function(input_file) {
  file.path(
    dirname(normalizePath(input_file, mustWork = FALSE)),
    paste0(
      strip_table_extensions(input_file),
      "_with_Kawalek_CRISPRi_scores.tsv"
    )
  )
}

if (is.null(OUTPUT_FILE)) {
  OUTPUT_FILE <- make_default_output(INPUT_FILE)
}

