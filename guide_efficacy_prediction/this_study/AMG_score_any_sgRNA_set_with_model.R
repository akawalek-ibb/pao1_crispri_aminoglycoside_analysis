# own data. Setting OUTPUT_FILE to NULL writes beside
# INPUT_FILE using:
#   <input_name>_with_Kawalek_CRISPRi_scores.tsv
OUTPUT_FILE <- file.path("guide_efficacy_prediction", "this_study", "out_user_scores", "example_PA2851_efp_scored.tsv")

# Stop if any perfect-design row lacks off_target_n when the deployed
# model actually uses the off-target feature.
STRICT_OFFTARGET_COVERAGE <- TRUE

# Overwrite an existing output file.
OVERWRITE_OUTPUT <- TRUE

# Keep the complete scored table in the RStudio Global Environment.
ASSIGN_RESULT_OBJECT <- TRUE
