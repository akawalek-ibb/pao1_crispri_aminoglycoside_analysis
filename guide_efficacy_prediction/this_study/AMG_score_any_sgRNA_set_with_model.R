#!/usr/bin/env Rscript
# Apply the preserved PAO1 guide model to user-supplied full-match guides.
# This is deployment scoring, not a held-out validation analysis. No screen
# results, phenotype measurements, model refitting or other scripts are needed.
# Default input: ten real efp (PA2851) guides from the manuscript library in
# Hawkins-style columns. Replace INPUT_FILE to score your own candidate table.
# Higher scores rank guides as stronger within a gene; scores are not 0-1
# transcript-knockdown fractions. All original input columns are preserved.
# Run from the manuscript project root; Source this complete file in RStudio.
# Model: guide_efficacy_prediction/this_study/CRISPRi_guide_efficacy_model.rds.
# Input: guide_efficacy_prediction/this_study/input/example_PA2851_efp_guides.csv.
# Output: guide_efficacy_prediction/this_study/out_user_scores/example_PA2851_efp_scored.tsv.
# The bundled model is ready to use. A new model is generated by
# Figure_scripts/FigS8/AMG_FigS8C_F_train_evaluate_model.R and must be selected
# explicitly with MODEL_FILE; no training step is required for the example.


############################################################
## Score an arbitrary guide-design table with the
## Kawalek P. aeruginosa CRISPRi guide-efficacy model.
##
## RStudio use:
##   1. Edit the USER SETTINGS section below.
##   2. Open this script in RStudio.
##   3. Click Source.
##
## Required input columns:
##   locus_tag, sgrna, pam, downstream, offset, off_target_n
##
## All original columns are preserved. Model scores and
## within-gene ranks are appended at the end.
############################################################

suppressPackageStartupMessages({
  library(data.table)
  library(glmnet)
})

