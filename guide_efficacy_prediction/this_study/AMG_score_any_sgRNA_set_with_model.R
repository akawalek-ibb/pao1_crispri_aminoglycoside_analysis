# HELPERS
# ============================================================

valid_dna <- function(x, expected_length) {
  x <- toupper(gsub("\\s+", "", as.character(x)))
  
  !is.na(x) &
    nchar(x) == expected_length &
    grepl(
      paste0("^[ACGT]{", expected_length, "}$"),
      x
    )
}

one_hot_acg <- function(seqs, prefix) {
  seqs <- toupper(gsub("\\s+", "", as.character(seqs)))
  
  if (length(seqs) == 0L) {
    stop("No sequences were supplied to one_hot_acg().")
  }
  
  lengths <- unique(nchar(seqs))
  
  if (length(lengths) != 1L || !is.finite(lengths[[1L]])) {
    stop("Sequences supplied to one_hot_acg() have unequal lengths.")
  }
  
  npos <- lengths[[1L]]
  
  X <- matrix(
    0,
    nrow = length(seqs),
    ncol = npos * 3L
  )
  
  colnames(X) <- paste0(
    prefix,
    rep(seq_len(npos), each = 3L),
    "_",
    rep(c("A", "C", "G"), times = npos)
  )
  
  for (position in seq_len(npos)) {
    base <- substr(seqs, position, position)
    first_col <- (position - 1L) * 3L
    
    X[, first_col + 1L] <- as.numeric(base == "A")
    X[, first_col + 2L] <- as.numeric(base == "C")
    X[, first_col + 3L] <- as.numeric(base == "G")
  }
  
  as.data.frame(X, check.names = FALSE)
}

build_full_design_matrix <- function(df) {
  required <- c(
    "spacer",
    "pam",
    "downstream_model",
    "offset",
    "off_target_n"
  )
  
  missing <- setdiff(required, names(df))
  
  if (length(missing) > 0L) {
    stop(
      "Missing feature columns while constructing model matrix: ",
      paste(missing, collapse = ", ")
    )
  }
  
  spacer_X <- one_hot_acg(df$spacer, "spacer_")
  downstream_X <- one_hot_acg(df$downstream_model, "down_")
  
  pam_n <- substr(df$pam, 1L, 1L)
  
  pam_X <- data.frame(
    pam_1_A = as.numeric(pam_n == "A"),
    pam_1_C = as.numeric(pam_n == "C"),
    pam_1_G = as.numeric(pam_n == "G"),
    check.names = FALSE
  )
  
  meta_X <- data.frame(
    offset_log1p = log1p(pmax(as.numeric(df$offset), 0)),
    offtarget_log1p = log1p(pmax(as.numeric(df$off_target_n), 0)),
    check.names = FALSE
  )
  
  data.frame(
    spacer_X,
    pam_X,
    downstream_X,
    meta_X,
    check.names = FALSE
  )
}

select_deployed_features <- function(X, deployed_feature_set) {
  switch(
    deployed_feature_set,
    
    sequence_only = X[
      ,
      !names(X) %in% c("offset_log1p", "offtarget_log1p"),
      drop = FALSE
    ],
    
    sequence_offset = X[
      ,
      names(X) != "offtarget_log1p",
      drop = FALSE
    ],
    
    sequence_offset_offtarget = X,
    
    stop(
      "Unknown deployed feature set in model bundle: ",
      deployed_feature_set
    )
  )
}

standardize_for_scoring <- function(input_dt) {
  required_input <- c(
    "locus_tag",
    "sgrna",
    "pam",
    "downstream",
    "offset",
    "off_target_n"
  )
  
  missing <- setdiff(required_input, names(input_dt))
  
  if (length(missing) > 0L) {
    stop(
      "Input file is missing required column(s): ",
      paste(missing, collapse = ", "),
      "\nAvailable columns:\n",
      paste(names(input_dt), collapse = ", ")
    )
  }
  
  score_dt <- copy(input_dt)
  score_dt[, input_row_order__ := .I]
  
  score_dt[
    ,
    `:=`(
      locus_id__ = as.character(locus_tag),
      spacer__ = toupper(gsub("\\s+", "", as.character(sgrna))),
      pam__ = toupper(gsub("\\s+", "", as.character(pam))),
      downstream_full__ = toupper(
        gsub("\\s+", "", as.character(downstream))
      ),
      offset__ = suppressWarnings(as.numeric(offset)),
      off_target_n__ = suppressWarnings(as.numeric(off_target_n))
    )
  ]
  
  score_dt
}

check_model_bundle <- function(bundle) {
  if (is.null(bundle$model)) {
    stop("The RDS file does not contain bundle$model.")
  }
  
  required_model_fields <- c(
    "cvfit",
    "lambda",
    "deployed_feature_set",
    "feature_names",
    "spacer_length",
    "downstream_length",
    "use_offset",
    "use_offtarget"
  )
  
  missing <- setdiff(required_model_fields, names(bundle$model))
  
  if (length(missing) > 0L) {
    stop(
      "The model bundle is missing required field(s): ",
      paste(missing, collapse = ", ")
    )
  }
  
  invisible(TRUE)
}

score_guide_table <- function(input_dt, bundle) {
  check_model_bundle(bundle)
  
  dt <- standardize_for_scoring(input_dt)
  
  dt[
    ,
    downstream_model__ := substr(
      downstream_full__,
      1L,
      bundle$model$downstream_length
    )
  ]
  
  dt[
    ,
    kawalek_score_status := fcase(
      is.na(locus_id__) | locus_id__ == "",
      "missing_locus_tag",
      
      !valid_dna(spacer__, bundle$model$spacer_length),
      "invalid_sgrna",
      
      is.na(pam__) | !grepl("^[ACGT]GG$", pam__),
      "invalid_pam",
      
      !valid_dna(
        downstream_model__,
        bundle$model$downstream_length
      ),
      "invalid_downstream_context",
      
      !is.finite(offset__) & isTRUE(bundle$model$use_offset),
      "missing_offset",
      
      !is.finite(off_target_n__) &
        isTRUE(bundle$model$use_offtarget),
      "missing_off_target_n",
      
      default = "scorable"
    )
  ]
  
  if (
    isTRUE(STRICT_OFFTARGET_COVERAGE) &&
    isTRUE(bundle$model$use_offtarget)
  ) {
    missing_offtarget <- dt[
      kawalek_score_status == "missing_off_target_n"
    ]
    
    if (nrow(missing_offtarget) > 0L) {
      examples <- unique(
        missing_offtarget[
          ,
          .(
            locus_tag = as.character(locus_tag),
            sgrna = as.character(sgrna)
          )
        ]
      )[1:min(.N, 10L)]
      
      stop(
        nrow(missing_offtarget),
        " row(s) lack off_target_n, but the deployed model uses ",
        "the off-target feature.\nExamples:\n",
        paste(
          capture.output(print(examples)),
          collapse = "\n"
        )
      )
    }
  }
  
  dt[, kawalek_efficacy_score := NA_real_]
  
  score_index <- which(dt$kawalek_score_status == "scorable")
  
  if (length(score_index) > 0L) {
    message(
      "Constructing feature matrix for ",
      format(length(score_index), big.mark = ","),
      " scorable guides..."
    )
    
    model_input <- dt[
      score_index,
      .(
        spacer = spacer__,
        pam = pam__,
        downstream_model = downstream_model__,
        offset = offset__,
        off_target_n = off_target_n__
      )
    ]
    
    # Values for unused continuous predictors are temporarily set to zero
    # only so the complete candidate matrix can be built. The corresponding
    # columns are removed before prediction.
    if (!isTRUE(bundle$model$use_offset)) {
      model_input[, offset := 0]
    }
    
    if (!isTRUE(bundle$model$use_offtarget)) {
      model_input[, off_target_n := 0]
    }
    
    X_full <- build_full_design_matrix(model_input)
    
    X_score <- select_deployed_features(
      X_full,
      bundle$model$deployed_feature_set
    )
    
    missing_features <- setdiff(
      bundle$model$feature_names,
      colnames(X_score)
    )
    
    if (length(missing_features) > 0L) {
      for (feature in missing_features) {
        X_score[[feature]] <- 0
      }
    }
    
    extra_features <- setdiff(
      colnames(X_score),
      bundle$model$feature_names
    )
    
    if (length(extra_features) > 0L) {
      X_score <- X_score[
        ,
        setdiff(colnames(X_score), extra_features),
        drop = FALSE
      ]
    }
    
    X_score <- X_score[
      ,
      bundle$model$feature_names,
      drop = FALSE
    ]
    
    message("Applying Kawalek CRISPRi model...")
    
    dt$kawalek_efficacy_score[score_index] <- as.numeric(
      predict(
        bundle$model$cvfit,
        newx = as.matrix(X_score),
        s = bundle$model$lambda,
        type = "link"
      )
    )
  }
  
  message("Calculating within-gene centered scores and ranks...")
  
  dt[
    ,
    kawalek_score_centered_within_gene := {
      values <- kawalek_efficacy_score
      
      if (all(!is.finite(values))) {
        rep(NA_real_, .N)
      } else {
        values - median(values, na.rm = TRUE)
      }
    },
    by = locus_id__
  ]
  
  dt[
    ,
    kawalek_rank_within_gene := frank(
      -kawalek_efficacy_score,
      ties.method = "min",
      na.last = "keep"
    ),
    by = locus_id__
  ]
  
  dt[
    ,
    `:=`(
      kawalek_model_feature_set = as.character(
        bundle$model$deployed_feature_set
      ),
      kawalek_model_lambda = as.numeric(bundle$model$lambda),
      kawalek_model_spacer_length = as.integer(
        bundle$model$spacer_length
      ),
      kawalek_model_downstream_length = as.integer(
        bundle$model$downstream_length
      ),
      kawalek_model_name = "Kawalek_CRISPRi_guide_efficacy_model"
    )
  ]
  
  setorder(dt, input_row_order__)
  
  internal_columns <- c(
    "input_row_order__",
    "locus_id__",
    "spacer__",
    "pam__",
    "downstream_full__",
    "downstream_model__",
    "offset__",
    "off_target_n__"
  )
  
  dt[, (internal_columns) := NULL]
  
  appended_columns <- c(
    "kawalek_efficacy_score",
    "kawalek_score_centered_within_gene",
    "kawalek_rank_within_gene",
    "kawalek_score_status",
    "kawalek_model_feature_set",
    "kawalek_model_lambda",
    "kawalek_model_spacer_length",
    "kawalek_model_downstream_length",
    "kawalek_model_name"
  )
  
  original_columns <- setdiff(names(dt), appended_columns)
  
  setcolorder(
    dt,
    c(original_columns, appended_columns)
  )
  
  dt
}

write_scored_table <- function(dt, output_file) {
  dir.create(
    dirname(output_file),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  if (file.exists(output_file) && !isTRUE(OVERWRITE_OUTPUT)) {
    stop(
      "Output file already exists and OVERWRITE_OUTPUT = FALSE:\n",
      output_file
    )
  }
  
  output_lower <- tolower(output_file)
  
  separator <- if (
    grepl("\\.csv(\\.gz)?$", output_lower)
  ) {
    ","
  } else {
    "\t"
  }
  
  fwrite(
    dt,
    file = output_file,
    sep = separator,
    quote = separator == ",",
    na = "NA"
  )
}

