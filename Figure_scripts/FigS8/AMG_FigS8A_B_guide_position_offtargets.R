feature_first <- function(x) {
  x <- x[!is.na(x) & as.character(x) != ""]
  if (length(x) == 0) return(NA)
  x[1]
}

# Hierarchical aggregation prevents B1 from receiving double weight
# simply because both T1 and T2 profiles are available. First
# summarize profiles within each batch, then summarize batches.
# Summarize B1 T1/T2 together first, then give each independent batch one contribution.
