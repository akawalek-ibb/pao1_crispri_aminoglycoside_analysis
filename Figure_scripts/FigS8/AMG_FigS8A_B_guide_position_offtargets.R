# ------------------------------------------------------------
# Continuous piecewise model helper
#
# y = b0 + b1 * min(offset, breakpoint)
#          + b2 * max(offset - breakpoint, 0)
#
# b1 is the slope before the breakpoint and b2 is the slope after it.
# ------------------------------------------------------------

fit_piecewise_candidate <- function(
    dat,
    breakpoint,
    weight_multiplier = NULL
) {
  dat <- data.table::as.data.table(dat)[
    is.finite(offset) &
      is.finite(relative_guide_effect) &
      !is.na(PAO1_ID) &
      PAO1_ID != ""
  ]
  
  n_left <- sum(dat$offset <= breakpoint)
  n_right <- sum(dat$offset > breakpoint)
  n_genes_left <- data.table::uniqueN(dat[offset <= breakpoint, PAO1_ID])
  n_genes_right <- data.table::uniqueN(dat[offset > breakpoint, PAO1_ID])
  
  if (
    n_left < BREAKPOINT_MIN_GUIDES_EACH_SIDE ||
    n_right < BREAKPOINT_MIN_GUIDES_EACH_SIDE ||
    n_genes_left < BREAKPOINT_MIN_GENES_EACH_SIDE ||
    n_genes_right < BREAKPOINT_MIN_GENES_EACH_SIDE
  ) {
    return(NULL)
  }
  
  if (is.null(weight_multiplier)) {
    w <- dat$gene_equal_weight
  } else {
    w <- dat$gene_equal_weight * weight_multiplier
  }
  
  keep <- is.finite(w) & w > 0
  dat <- dat[keep]
  w <- w[keep]
  
  if (nrow(dat) < 5L) return(NULL)
  
  x_before <- pmin(dat$offset, breakpoint)
  x_after <- pmax(dat$offset - breakpoint, 0)
  
  X <- cbind(
    intercept = 1,
    offset_before = x_before,
    offset_after = x_after
  )
  
  fit <- tryCatch(
    stats::lm.wfit(
      x = X,
      y = dat$relative_guide_effect,
      w = w
    ),
    error = function(e) NULL
  )
  
  if (is.null(fit) || any(!is.finite(fit$coefficients))) {
    return(NULL)
  }
  
  weighted_rss <- sum(w * fit$residuals^2, na.rm = TRUE)
  
  data.table::data.table(
    breakpoint_bp = breakpoint,
    weighted_rss = weighted_rss,
    intercept = unname(fit$coefficients["intercept"]),
    slope_before = unname(fit$coefficients["offset_before"]),
    slope_after = unname(fit$coefficients["offset_after"]),
    n_guides_left = n_left,
    n_guides_right = n_right,
    n_genes_left = n_genes_left,
    n_genes_right = n_genes_right
  )
}

scan_piecewise_breakpoints <- function(
    dat,
    candidate_breakpoints,
    weight_multiplier = NULL
) {
  data.table::rbindlist(
    lapply(
      candidate_breakpoints,
      function(bp) {
        fit_piecewise_candidate(
          dat = dat,
          breakpoint = bp,
          weight_multiplier = weight_multiplier
        )
      }
    ),
    use.names = TRUE,
    fill = TRUE
  )
}

