# Per-gene associations are useful as a robustness summary because they do
# not allow between-gene differences in essentiality to drive the result.
per_gene_offtarget <- offtarget_df[
  ,
  .(
    n_guides = .N,
    n_distinct_offtarget = data.table::uniqueN(off_target_n),
    spearman_offtarget_vs_LFC = safe_cor(
      off_target_n,
      LFC_agg,
      "spearman"
    ),
    spearman_offtarget_vs_centered_LFC = safe_cor(
      off_target_n,
      LFC_centered_agg,
      "spearman"
    ),
    pearson_offtarget_vs_centered_LFC = safe_cor(
      off_target_n,
      LFC_centered_agg,
      "pearson"
    )
  ),
  by = .(essential_status, PAO1_ID, gene_name)
][
  n_guides >= MIN_GUIDES_PER_GENE_COR &
    n_distinct_offtarget >= MIN_DISTINCT_OFFTARGET_COR
]

# Descriptive correlations plus their nominal p-values. Spearman is the
# primary descriptive statistic because off_target_n is a discrete count.
offtarget_cor <- data.table::rbindlist(
  lapply(
    levels(droplevels(offtarget_df$essential_status)),
    function(status_i) {
      dat_i <- offtarget_df[essential_status == status_i]
      
      sp_raw <- safe_cor_test(dat_i$off_target_n, dat_i$LFC_agg, "spearman")
      pe_raw <- safe_cor_test(dat_i$off_target_n, dat_i$LFC_agg, "pearson")
      sp_ctr <- safe_cor_test(
        dat_i$off_target_n,
        dat_i$LFC_centered_agg,
        "spearman"
      )
      pe_ctr <- safe_cor_test(
        dat_i$off_target_n,
        dat_i$LFC_centered_agg,
        "pearson"
      )
      
      clustered <- cluster_robust_slope(
        dat_i,
        x_col = "off_target_n",
        y_col = "LFC_centered_agg",
        cluster_col = "PAO1_ID"
      )
      
      gene_i <- per_gene_offtarget[essential_status == status_i]
      
      data.table::data.table(
        essential_status = status_i,
        n_guides = nrow(dat_i),
        n_genes = data.table::uniqueN(dat_i$PAO1_ID),
        raw_spearman_rho = sp_raw$estimate,
        raw_spearman_p = sp_raw$p_value,
        raw_pearson_r = pe_raw$estimate,
        raw_pearson_p = pe_raw$p_value,
        centered_spearman_rho = sp_ctr$estimate,
        centered_spearman_p = sp_ctr$p_value,
        centered_pearson_r = pe_ctr$estimate,
        centered_pearson_p = pe_ctr$p_value,
        clustered_linear_slope = clustered$slope,
        clustered_linear_robust_se = clustered$robust_se,
        clustered_linear_t = clustered$t_value,
        clustered_linear_p = clustered$p_value,
        clustered_linear_n_clusters = clustered$n_clusters,
        clustered_linear_r_squared = clustered$r_squared,
        n_genes_with_within_gene_correlation = nrow(gene_i),
        median_per_gene_spearman_rho = if (
          nrow(gene_i) > 0L
        ) {
          stats::median(
            gene_i$spearman_offtarget_vs_centered_LFC,
            na.rm = TRUE
          )
        } else {
          NA_real_
        }
      )
    }
  ),
  use.names = TRUE,
  fill = TRUE
)

