safe_cor <- function(x, y, method = "spearman") {
  ok <- is.finite(x) & is.finite(y)
  if (sum(ok) < 3L) return(NA_real_)
  if (dplyr::n_distinct(x[ok]) < 2L) return(NA_real_)
  if (dplyr::n_distinct(y[ok]) < 2L) return(NA_real_)
  suppressWarnings(stats::cor(x[ok], y[ok], method = method))
}

safe_cor_test <- function(x, y, method = "spearman") {
  ok <- is.finite(x) & is.finite(y)
  x <- x[ok]
  y <- y[ok]
  
  if (
    length(x) < 3L ||
    dplyr::n_distinct(x) < 2L ||
    dplyr::n_distinct(y) < 2L
  ) {
    return(list(estimate = NA_real_, p_value = NA_real_, n = length(x)))
  }
  
  test <- tryCatch(
    stats::cor.test(
      x,
      y,
      method = method,
      exact = if (identical(method, "spearman")) FALSE else NULL
    ),
    error = function(e) NULL
  )
  
  if (is.null(test)) {
    return(list(estimate = NA_real_, p_value = NA_real_, n = length(x)))
  }
  
  list(
    estimate = unname(test$estimate),
    p_value = test$p.value,
    n = length(x)
  )
}

# Linear trend with a cluster-robust standard error. Guides are clustered
# by gene, so ordinary lm() standard errors would treat non-independent
# guides from the same gene as independent observations.
cluster_robust_slope <- function(
    data,
    x_col = "off_target_n",
    y_col = "LFC_centered_agg",
    cluster_col = "PAO1_ID"
) {
  dat <- data.table::as.data.table(data)[
    is.finite(get(x_col)) &
      is.finite(get(y_col)) &
      !is.na(get(cluster_col)) &
      as.character(get(cluster_col)) != ""
  ]
  
  dat <- dat[
    ,
    .(
      x = as.numeric(get(x_col)),
      y = as.numeric(get(y_col)),
      cluster = as.character(get(cluster_col))
    )
  ]
  
  n_obs <- nrow(dat)
  n_clusters <- data.table::uniqueN(dat$cluster)
  
  if (
    n_obs < 5L ||
    n_clusters < 3L ||
    data.table::uniqueN(dat$x) < 2L ||
    data.table::uniqueN(dat$y) < 2L
  ) {
    return(data.table::data.table(
      slope = NA_real_,
      robust_se = NA_real_,
      t_value = NA_real_,
      p_value = NA_real_,
      n_obs = n_obs,
      n_clusters = n_clusters,
      r_squared = NA_real_
    ))
  }
  
  fit <- stats::lm(y ~ x, data = dat)
  X <- stats::model.matrix(fit)
  residuals_fit <- stats::residuals(fit)
  k <- ncol(X)
  
  bread <- tryCatch(
    solve(crossprod(X)),
    error = function(e) NULL
  )
  
  if (is.null(bread)) {
    return(data.table::data.table(
      slope = NA_real_,
      robust_se = NA_real_,
      t_value = NA_real_,
      p_value = NA_real_,
      n_obs = n_obs,
      n_clusters = n_clusters,
      r_squared = summary(fit)$r.squared
    ))
  }
  
  meat <- matrix(0, nrow = k, ncol = k)
  cluster_index <- split(seq_len(n_obs), dat$cluster)
  
  for (idx in cluster_index) {
    Xg <- X[idx, , drop = FALSE]
    ug <- residuals_fit[idx]
    score_g <- crossprod(Xg, ug)
    meat <- meat + score_g %*% t(score_g)
  }
  
  correction <-
    (n_clusters / (n_clusters - 1)) *
    ((n_obs - 1) / (n_obs - k))
  
  vcov_cluster <- correction * bread %*% meat %*% bread
  robust_se <- sqrt(diag(vcov_cluster))["x"]
  slope <- stats::coef(fit)["x"]
  
  if (!is.finite(robust_se) || robust_se <= 0) {
    t_value <- NA_real_
    p_value <- NA_real_
  } else {
    t_value <- slope / robust_se
    p_value <- 2 * stats::pt(
      abs(t_value),
      df = n_clusters - 1L,
      lower.tail = FALSE
    )
  }
  
  data.table::data.table(
    slope = unname(slope),
    robust_se = unname(robust_se),
    t_value = unname(t_value),
    p_value = unname(p_value),
    n_obs = n_obs,
    n_clusters = n_clusters,
    r_squared = summary(fit)$r.squared
  )
}

format_p <- function(p) {
  # Vectorised formatter: works for a scalar or an entire numeric column.
  vapply(
    p,
    function(x) {
      if (length(x) != 1L || !is.finite(x)) return("NA")
      if (x < 2.2e-16) return("<2.2e-16")
      format.pval(x, digits = 2, eps = 1e-300)
    },
    character(1)
  )
}

