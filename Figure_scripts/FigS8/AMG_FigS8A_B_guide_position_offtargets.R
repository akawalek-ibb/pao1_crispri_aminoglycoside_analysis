# ------------------------------------------------------------
# Gene-level bootstrap for breakpoint uncertainty
#
# Genes are sampled with replacement. Instead of physically duplicating
# guide rows, the number of times each gene is sampled is used as an
# additional weight multiplier. This is equivalent to cluster resampling
# but substantially faster.
# ------------------------------------------------------------

set.seed(BREAKPOINT_SEED)

bootstrap_gene_ids <- unique(offset_df$PAO1_ID)
n_bootstrap_genes <- length(bootstrap_gene_ids)

bootstrap_min <- max(
  BREAKPOINT_SEARCH_MIN_BP,
  estimated_breakpoint - BREAKPOINT_BOOTSTRAP_WINDOW_BP
)
bootstrap_max <- min(
  BREAKPOINT_SEARCH_MAX_BP,
  estimated_breakpoint + BREAKPOINT_BOOTSTRAP_WINDOW_BP
)

bootstrap_candidates <- sort(unique(c(
  seq(
    bootstrap_min,
    bootstrap_max,
    by = BREAKPOINT_BOOTSTRAP_STEP_BP
  ),
  estimated_breakpoint
)))

bootstrap_breakpoints <- rep(NA_real_, BREAKPOINT_BOOTSTRAP_N)

for (bb in seq_len(BREAKPOINT_BOOTSTRAP_N)) {
  sampled_genes <- sample(
    bootstrap_gene_ids,
    size = n_bootstrap_genes,
    replace = TRUE
  )
  
  multiplicity <- data.table::data.table(
    PAO1_ID = sampled_genes
  )[
    ,
    .(bootstrap_multiplicity = .N),
    by = PAO1_ID
  ]
  
  boot_dat <- merge(
    offset_df,
    multiplicity,
    by = "PAO1_ID",
    all = FALSE,
    sort = FALSE
  )
  
  boot_scan <- scan_piecewise_breakpoints(
    dat = boot_dat,
    candidate_breakpoints = bootstrap_candidates,
    weight_multiplier = boot_dat$bootstrap_multiplicity
  )
  
  if (nrow(boot_scan) > 0L) {
    bootstrap_breakpoints[bb] <- boot_scan[which.min(weighted_rss), breakpoint_bp]
  }
  
  if (bb %% 50L == 0L) {
    message(
      "  S8A breakpoint bootstrap: ",
      bb, "/", BREAKPOINT_BOOTSTRAP_N
    )
  }
}

