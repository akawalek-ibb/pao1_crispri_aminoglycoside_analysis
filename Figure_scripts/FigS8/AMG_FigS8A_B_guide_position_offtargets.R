    stop(
      "No perfect-guide rows found for ", profile_label,
      " / ", condition_id
    )
  }
  
  profile_tbl <- merge(
    profile_tbl,
    unique(raw_join[, ..feature_cols]),
    by = "spacer",
    all.x = TRUE,
    suffixes = c("", ".feature")
  )
  
  # Coalesce duplicated metadata after the merge.
  for (nm in c("PAO1_ID", "offset")) {
    feature_nm <- paste0(nm, ".feature")
    if (feature_nm %in% names(profile_tbl)) {
      if (!nm %in% names(profile_tbl)) {
        data.table::setnames(profile_tbl, feature_nm, nm)
      } else {
        profile_tbl[
          is.na(get(nm)) | as.character(get(nm)) == "",
          (nm) := get(feature_nm)
        ]
        profile_tbl[, (feature_nm) := NULL]
      }
    }
  }
  
  profile_tbl[
    ,
    `:=`(
      batch = batch_id,
      profile_label = profile_label,
      profile_order = CONTROL_MANIFEST$profile_order[i],
      LFC.adj = as.numeric(LFC.adj),
      offset = suppressWarnings(as.numeric(offset)),
      off_target_n = suppressWarnings(as.numeric(off_target_n)),
      mean_T0_count = suppressWarnings(as.numeric(mean_T0_count))
    )
  ]
  
  profile_tbl <- profile_tbl[
    is.finite(LFC.adj) &
      is.finite(mean_T0_count) &
      mean_T0_count >= MIN_MEAN_T0
  ]
  
  # Center within gene and profile for a confounding-resistant QC metric.
  profile_tbl[
    ,
    LFC_centered := LFC.adj - stats::median(LFC.adj, na.rm = TRUE),
    by = .(profile_label, PAO1_ID)
  ]
  
  profile_data_list[[i]] <- profile_tbl
  
  gene_call_tbl <- median_tbl[
    condition == condition_id &
      !is.na(PAO1_ID) &
      PAO1_ID != ""
  ]
  
  gene_call_tbl[
    ,
    `:=`(
      batch = batch_id,
      profile_label = profile_label,
      profile_order = CONTROL_MANIFEST$profile_order[i],
      medLFC = as.numeric(medLFC),
      p_stouffer = as.numeric(p_stouffer),
      significant_negative =
        is.finite(p_stouffer) &
        p_stouffer < P_STOUFFER_CUT &
        is.finite(medLFC) &
        medLFC <= NEGATIVE_LFC_CUT
    )
  ]
  
  gene_call_list[[i]] <- gene_call_tbl
  
  rm(melted, median_tbl, raw_join, design)
  invisible(gc())
}

