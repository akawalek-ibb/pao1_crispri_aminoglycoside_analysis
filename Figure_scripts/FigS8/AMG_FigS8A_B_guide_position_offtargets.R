calculate_segment_correlations <- function(dat, segment_name) {
  out <- dat[
    ,
    .(
      n_guides = .N,
      n_distinct_offsets = data.table::uniqueN(offset),
      spearman_rho = safe_cor(
        offset,
        relative_guide_effect,
        method = "spearman"
      )
    ),
    by = .(PAO1_ID, gene_name)
  ]
  
  out <- out[
    n_guides >= MIN_GUIDES_PER_GENE_COR &
      n_distinct_offsets >= MIN_DISTINCT_OFFSET_COR &
      is.finite(spearman_rho)
  ]
  
  out[, segment := segment_name]
  out
}

