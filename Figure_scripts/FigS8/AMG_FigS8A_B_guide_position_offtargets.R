    )
  }
  
  raw_join[
    ,
    mean_T0_count := rowMeans(
      as.matrix(.SD),
      na.rm = TRUE
    ),
    .SDcols = t0_samples
  ]
  
  feature_cols <- intersect(
    c(
      "spacer", "PAO1_ID", "pam", "downstream", "offset",
      "off_target_n", "mean_T0_count"
    ),
    names(raw_join)
  )
  
  profile_tbl <- melted[
    condition == condition_id &
      type == "perfect" &
      !is.na(PAO1_ID) &
