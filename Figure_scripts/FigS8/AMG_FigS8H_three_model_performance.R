normalize_dna <- function(x) {
  toupper(gsub("\\s+", "", as.character(x)))
}

normalize_text <- function(x) {
  trimws(as.character(x))
}

as_numeric_safe <- function(x) {
  suppressWarnings(as.numeric(as.character(x)))
}

safe_cor <- function(x, y, method = "spearman") {
  keep <- is.finite(x) & is.finite(y)
  
  if (sum(keep) < 3L) {
    return(NA_real_)
  }
  
  x <- x[keep]
  y <- y[keep]
  
  if (
    length(unique(x)) < 2L ||
    length(unique(y)) < 2L
  ) {
    return(NA_real_)
  }
  
  suppressWarnings(
    stats::cor(
      x,
      y,
      method = method,
      use = "complete.obs"
    )
  )
}

first_nonmissing <- function(x) {
  x <- as.character(x)
  x <- x[!is.na(x) & x != ""]
  
  if (length(x) == 0L) {
    return(NA_character_)
  }
  
  x[[1L]]
}

first_existing_column <- function(
    dt,
    candidates,
    required = TRUE,
    description = "column"
) {
  hit <- candidates[candidates %in% names(dt)]
  
  if (length(hit) == 0L) {
    if (isTRUE(required)) {
      stop(
        "Could not identify ", description, ". Checked:\n",
        paste(candidates, collapse = ", "),
        "\nAvailable columns:\n",
        paste(names(dt), collapse = ", ")
      )
    }
    
    return(NULL)
  }
  
  hit[[1L]]
}

make_guide_key <- function(locus_tag, spacer, pam) {
