  )
}

align_feature_matrix <- function(
    X,
    feature_names
) {
  missing_features <- setdiff(
    feature_names,
    colnames(X)
  )
  
  if (length(missing_features) > 0L) {
    for (feature in missing_features) {
      X[[feature]] <- 0
    }
  }
  
  extra_features <- setdiff(
    colnames(X),
    feature_names
  )
  
  if (length(extra_features) > 0L) {
    X <- X[
      ,
      setdiff(colnames(X), extra_features),
      drop = FALSE
    ]
  }
  
  X[
    ,
    feature_names,
    drop = FALSE
  ]
}

make_group_folds <- function(
    groups,
    nfolds,
    seed
) {
  groups <- as.character(groups)
  unique_groups <- unique(groups)
  
  if (length(unique_groups) < 3L) {
    stop(
      "At least three genes are required for grouped inner CV."
    )
  }
  
  nfolds_use <- min(
    as.integer(nfolds),
    length(unique_groups)
  )
  
  set.seed(seed)
  shuffled <- sample(unique_groups)
  
  group_fold <- rep(
    seq_len(nfolds_use),
    length.out = length(shuffled)
  )
  
  names(group_fold) <- shuffled
  as.integer(group_fold[groups])
}

split_genes <- function(
    groups,
    validation_fraction,
    seed
) {
  genes <- unique(as.character(groups))
  
  if (length(genes) < 10L) {
    stop(
      "Too few genes for outer held-out validation."
    )
  }
  
  set.seed(seed)
  
  n_validation <- max(
    1L,
    floor(length(genes) * validation_fraction)
  )
  
  validation_genes <- sample(
    genes,
    n_validation
  )
  
  list(
    train_index = which(
      !groups %in% validation_genes
    ),
    validation_index = which(
      groups %in% validation_genes
    ),
    validation_genes = validation_genes
  )
}

fit_grouped_cv_lasso <- function(
    X,
    y,
    groups,
    seed,
    alpha,
    lambda_choice
) {
  foldid <- make_group_folds(
    groups = groups,
    nfolds = INNER_NFOLDS,
    seed = seed
  )
  
  cvfit <- glmnet::cv.glmnet(
    x = as.matrix(X),
    y = as.numeric(y),
    family = "gaussian",
    alpha = alpha,
    standardize = TRUE,
    intercept = TRUE,
    foldid = foldid,
    keep = FALSE
  )
  
  lambda <- switch(
    lambda_choice,
    "lambda.min" = cvfit$lambda.min,
    "lambda.1se" = cvfit$lambda.1se,
    stop(
      "Unknown lambda choice: ",
      lambda_choice
    )
  )
  
  list(
    cvfit = cvfit,
    lambda = lambda
  )
}

predict_grouped_lasso <- function(
    fitted_model,
    X
) {
  as.numeric(
    predict(
      fitted_model$cvfit,
      newx = as.matrix(X),
      s = fitted_model$lambda,
      type = "link"
    )
  )
}

