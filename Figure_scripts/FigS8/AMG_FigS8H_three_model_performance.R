        },
        by = .(
          PAO1_ID,
          gene_name
        )
      ]
      
      repeat_topk_list[[repeat_topk_index]] <- data.table(
        repeat_id = repeat_id,
        model = model_name,
        k = k,
        n_genes = nrow(topk_gene),
        mean_topk_enrichment = mean(
          topk_gene$topk_enrichment,
