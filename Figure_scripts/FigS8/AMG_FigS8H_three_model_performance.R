# - guide_efficacy_prediction/this_study/CRISPRi_guide_efficacy_model.rds and
#   model_training_guides_with_scores.tsv.gz.
# - Figure_scripts/FigS8/input_AMG_FigS8/PAO1_sgRNA_with_Pasteur_scores.tsv.gz and
