# ============================================================

# Resample whole genes for performance confidence intervals so linked guide
# observations from a gene travel together. This describes sampling uncertainty;
# the figure's boxplots do not perform pairwise model-superiority tests.
bootstrap_performance_model <- function(
    model_data,
    n_bootstrap,
    seed
) {
  genes <- unique(model_data$PAO1_ID)
  
  if (length(genes) < 3L) {
    stop(
      "Too few genes for performance bootstrap."
    )
  }
  
  bootstrap_results <- vector(
    "list",
    n_bootstrap
  )
  
  set.seed(seed)
  
  for (bootstrap_id in seq_len(n_bootstrap)) {
    sampled_genes <- sample(
      genes,
      length(genes),
      replace = TRUE
    )
    
    boot_data <- rbindlist(
      lapply(
        seq_along(sampled_genes),
        function(sample_index) {
          subset_data <- model_data[PAO1_ID == sampled_genes[[sample_index]]]
          
          subset_data[
            ,
            bootstrap_gene_id :=
              sample_index
          ]
          
          subset_data
        }
      ),
      use.names = TRUE,
      fill = TRUE
    )
    
    boot_gene_cor <- boot_data[
      ,
      .(
        spearman_r = safe_cor(
          predicted_strength_percentile,
          y,
          "spearman"
        )
      ),
      by = bootstrap_gene_id
    ]
    
    bootstrap_results[[bootstrap_id]] <- data.table(
      bootstrap_id = bootstrap_id,
      pooled_spearman = safe_cor(
        boot_data$predicted_strength_percentile,
        boot_data$y,
        "spearman"
      ),
      pooled_pearson = safe_cor(
        boot_data$predicted_strength_percentile,
        boot_data$y,
        "pearson"
      ),
      median_gene_spearman = median(
        boot_gene_cor$spearman_r,
        na.rm = TRUE
      ),
      proportion_genes_positive = mean(
        boot_gene_cor$spearman_r > 0,
        na.rm = TRUE
      )
    )
  }
  
  rbindlist(
    bootstrap_results,
    use.names = TRUE
  )
}

