  )
}

is_scorable_status <- function(x) {
  x <- tolower(trimws(as.character(x)))
  
  is.na(x) |
    x == "" |
    x %in% c(
      "scorable",
      "scored",
      "ok",
      "success"
    )
}

model_strength_percentile <- function(score) {
  score <- as.numeric(score)
  result <- rep(NA_real_, length(score))
  valid <- is.finite(score)
  n_valid <- sum(valid)
  
  if (n_valid == 0L) {
    return(result)
  }
  
  if (n_valid == 1L) {
    result[valid] <- 1
    return(result)
  }
  
  rank_best_first <- data.table::frank(
    -score[valid],
    ties.method = "average"
  )
  
  result[valid] <- 1 -
    (rank_best_first - 1) /
    (n_valid - 1)
  
  result
}

